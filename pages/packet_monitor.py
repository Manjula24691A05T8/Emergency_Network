import streamlit as st

from modules.message_transfer import PacketEvent


def _render_wireshark_guidance() -> None:
    with st.expander("Optional: inspect authorized traffic with Wireshark"):
        st.markdown(
            "This simulator creates packet records in Python; it does not transmit "
            "network frames. Its synthetic `10.20.0.0/16` addresses therefore will not "
            "appear in a Wireshark capture."
        )
        st.markdown(
            "To inspect real traffic separately, open Wireshark, select an interface "
            "you are authorized to monitor and start a capture, or open an authorized "
            "`.pcapng` capture file. This page does not import captures or mix captured "
            "packets with simulation records."
        )
        st.caption(
            "A future capture integration would need a separate PCAP reader and an "
            "explicit distinction between real captures and simulated packets."
        )


def render_packet_monitor() -> None:
    st.markdown('<div class="eyebrow">OBSERVABILITY / SIMULATED PACKETS</div>', unsafe_allow_html=True)
    st.title("Packet Monitoring")
    st.markdown(
        "Inspect packet records generated by the emergency-message simulation. "
        "This is simulated traffic, not a live capture or Wireshark feed."
    )

    events = st.session_state.get("packet_events", [])
    if not isinstance(events, list):
        st.error("Packet event state is invalid. Reload the application before continuing.")
        return
    records = [event for event in events if isinstance(event, PacketEvent)]
    if not records:
        st.info("No packets recorded yet. Queue and process a message in Emergency Communication.")
        _render_wireshark_guidance()
        return

    statuses = ["All", *dict.fromkeys(event.status for event in records)]
    selected_status = st.selectbox("Filter by status", statuses)
    priorities = ["All", *dict.fromkeys(event.priority for event in records)]
    selected_priority = st.selectbox("Filter by priority", priorities)
    filtered = [
        event
        for event in records
        if (selected_status == "All" or event.status == selected_status)
        and (selected_priority == "All" or event.priority == selected_priority)
    ]

    delivered = sum(event.status == "Delivered" for event in records)
    summary = st.columns(3)
    summary[0].metric("Recorded packets", len(records))
    summary[1].metric("Delivered", delivered)
    summary[2].metric("Failed", len(records) - delivered)

    lines = [
        "Packet ID | Source IP | Destination IP | Protocol | Bytes | Timestamp | Status | Delay (ms)"
    ]
    for event in filtered:
        delay = (
            f"{event.transmission_delay_ms:.2f}"
            if event.transmission_delay_ms is not None
            else "Not available"
        )
        lines.append(
            f"{event.packet_id} | {event.source_ip} | {event.destination_ip} | "
            f"{event.protocol} | {event.packet_size_bytes} | {event.timestamp} | "
            f"{event.status} | {delay}"
        )
    st.code("\n".join(lines), language="text")
    st.caption(f"Showing {len(filtered)} of {len(records)} simulated records.")
    _render_wireshark_guidance()


render_packet_monitor()
